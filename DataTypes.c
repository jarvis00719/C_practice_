#include <stdio.h>

int main(){
     
    // integer - int - %d or %i
    int age, weight;
    age = 25; weight = 60;
    
    // (floating-point) - float - %f
    float height = 6.123456789;
    
    
    // (double-precision floating-point) - double - %lf
    double pi = 6.123456789;
    
    
    
    // characters - char - %c
    char grade = 'A'; 
    printf("grade = %c\n", grade);
    printf("Age = %d\n",age);           
    printf("Weight = %d\n", weight);

/*double*/   printf("pi = %Lf\n", pi);
/*float*/    printf("Height = %f\n",height);
    



  return 0;
}
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    


